func TestFormatDefault_MySQLBooleanAndFunctions(t *testing.T) {
	g := NewDefaultMigrationGenerator("mysql")
	diff := &SchemaDiff{
		HasChanges: true,
		TablesAdded: []Table{
			{
				Name: "events",
				Columns: []Column{
					{Name: "flag", Type: "boolean", Default: false, Nullable: false},
					{Name: "created", Type: "timestamp", Default: "NOW()", Nullable: false},
					{Name: "label", Type: "varchar", Length: 20, Default: "o'clock", Nullable: false},
				},
			},
		},
	}
	up, err := g.GenerateUp(context.Background(), diff, nil)
	if err != nil {
		t.Fatalf("GenerateUp: %v", err)
	}
	// MySQL renders boolean false as 0.
	if !strings.Contains(up, "DEFAULT 0") {
		t.Errorf("expected mysql boolean false as DEFAULT 0:\n%s", up)
	}
	// Function-style defaults are emitted verbatim (no quoting).
	if !strings.Contains(up, "DEFAULT NOW()") {
		t.Errorf("expected function default NOW() unquoted:\n%s", up)
	}
	// String defaults are single-quoted with embedded quotes escaped.
	if !strings.Contains(up, "'o''clock'") {
		t.Errorf("expected escaped string default:\n%s", up)
	}
}
