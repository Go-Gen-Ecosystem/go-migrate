func TestGenerate_ProducesUpAndDownAndMetadata(t *testing.T) {
	g := NewDefaultMigrationGenerator("postgresql")
	desired := &DatabaseSchema{Version: "2.0.0"}
	diff := &SchemaDiff{
		HasChanges: true,
		TablesAdded: []Table{
			{
				Name: "accounts",
				Columns: []Column{
					{Name: "id", Type: "integer", AutoIncrement: true, Nullable: false},
					{Name: "email", Type: "varchar", Length: 255, Nullable: false},
				},
				PrimaryKey: []string{"id"},
			},
		},
		Summary: DiffSummary{TablesAdded: 1, TotalChanges: 1, SafeToApply: true},
	}

	mig, err := g.Generate(context.Background(), diff, desired)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if mig.Version != "2.0.0" {
		t.Errorf("expected version from desired schema, got %s", mig.Version)
	}
	if !strings.Contains(mig.UpSQL, "CREATE TABLE") {
		t.Errorf("UP SQL missing CREATE TABLE:\n%s", mig.UpSQL)
	}
	if !strings.Contains(mig.UpSQL, "PRIMARY KEY") {
		t.Errorf("UP SQL missing PRIMARY KEY:\n%s", mig.UpSQL)
	}
	// The added table must be dropped by the DOWN migration.
	if !strings.Contains(mig.DownSQL, "DROP TABLE") {
		t.Errorf("DOWN SQL missing DROP TABLE:\n%s", mig.DownSQL)
	}
	if !mig.SafeToAutoApply {
		t.Error("additive change should be marked safe to auto-apply")
	}
	if mig.Description == "" {
		t.Error("expected a generated description")
	}
}

func TestGenerateUp_ColumnConstraintsAndDefaults(t *testing.T) {
	g := NewDefaultMigrationGenerator("postgresql")
	diff := &SchemaDiff{
		HasChanges: true,
		TablesAdded: []Table{
			{
				Name: "products",
				Columns: []Column{
					{Name: "id", Type: "integer", AutoIncrement: true, Nullable: false},
					{Name: "name", Type: "varchar", Length: 100, Nullable: false},
					{Name: "active", Type: "boolean", Default: true, Nullable: false},
					{Name: "sku", Type: "varchar", Length: 50, Unique: true},
					{Name: "price", Type: "decimal", Precision: 10, Scale: 2},
				},
				PrimaryKey: []string{"id"},
			},
		},
	}
	up, err := g.GenerateUp(context.Background(), diff, nil)
	if err != nil {
		t.Fatalf("GenerateUp: %v", err)
	}

	checks := []string{
		"NOT NULL",                       // non-nullable columns
		"GENERATED BY DEFAULT AS IDENTITY", // postgres auto-increment
		"DEFAULT true",                   // boolean default in postgres
		"UNIQUE",                         // unique column
		"varchar(100)",                   // length formatting
		"decimal(10,2)",                  // precision/scale formatting
	}
	for _, c := range checks {
		if !strings.Contains(up, c) {
			t.Errorf("UP SQL missing %q:\n%s", c, up)
		}
	}
}

