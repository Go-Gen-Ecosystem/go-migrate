func TestGenerateUp_IndexesConstraintsViews(t *testing.T) {
	g := NewDefaultMigrationGenerator("postgresql")
	diff := &SchemaDiff{
		HasChanges: true,
		IndexesAdded: []Index{
			{Name: "idx_users_email", Table: "users", Columns: []string{"email"}, Unique: true},
		},
		IndexesDropped: []Index{
			{Name: "idx_old", Table: "users", Columns: []string{"old"}},
		},
		ConstraintsAdded: []Constraint{
			{Name: "fk_orders_user", Table: "orders", Type: "foreign_key",
				Columns: []string{"user_id"}, ReferencedTable: "users",
				ReferencedColumns: []string{"id"}, OnDelete: "CASCADE"},
			{Name: "uq_users_email", Table: "users", Type: "unique", Columns: []string{"email"}},
			{Name: "ck_price", Table: "products", Type: "check", CheckExpression: "price > 0"},
		},
		ConstraintsDropped: []Constraint{
			{Name: "old_con", Table: "users", Type: "unique", Columns: []string{"x"}},
		},
		ViewsAdded: []View{
			{Name: "active_users", Query: "SELECT * FROM users WHERE active = true"},
		},
		ViewsDropped: []View{
			{Name: "old_view", Query: "SELECT 1"},
		},
		TriggersAdded: []Trigger{
			{Name: "trg_audit", Table: "users"},
		},
		TriggersDropped: []Trigger{
			{Name: "trg_old", Table: "users"},
		},
	}
	up, err := g.GenerateUp(context.Background(), diff, nil)
	if err != nil {
		t.Fatalf("GenerateUp: %v", err)
	}

	checks := []string{
		"CREATE UNIQUE INDEX",           // unique index add
		"DROP INDEX IF EXISTS",          // index drop
		"FOREIGN KEY",                   // FK constraint
		"ON DELETE CASCADE",             // FK on-delete clause
		"ADD CONSTRAINT",                // constraint add
		"UNIQUE (",                      // unique constraint
		"CHECK (price > 0)",             // check constraint
		"DROP CONSTRAINT IF EXISTS",     // constraint drop
		"CREATE VIEW",                   // view add
		"DROP VIEW IF EXISTS",           // view drop
		"DROP TRIGGER IF EXISTS",        // trigger drop
	}
	for _, c := range checks {
		if !strings.Contains(up, c) {
			t.Errorf("UP SQL missing %q:\n%s", c, up)
		}
	}
}

func TestGenerateDown_DropsAddedAndRecreatesDropped(t *testing.T) {
	g := NewDefaultMigrationGenerator("postgresql")
	diff := &SchemaDiff{
		HasChanges: true,
		TablesAdded: []Table{
			{Name: "added", Columns: []Column{{Name: "id", Type: "integer"}}},
		},
		TablesDropped: []Table{
			{Name: "removed", Columns: []Column{{Name: "id", Type: "integer"}}},
		},
		TablesModified: []TableDiff{
			{TableName: "changed", ColumnsAdded: []Column{{Name: "c", Type: "text"}}},
		},
	}
	down, err := g.GenerateDown(context.Background(), diff, nil)
	if err != nil {
		t.Fatalf("GenerateDown: %v", err)
	}
	// DOWN drops the table that UP added.
	if !strings.Contains(down, `DROP TABLE IF EXISTS "added"`) {
		t.Errorf("DOWN should drop the added table:\n%s", down)
	}
	// DOWN recreates the table that UP dropped.
	if !strings.Contains(down, `CREATE TABLE "removed"`) {
		t.Errorf("DOWN should recreate the dropped table:\n%s", down)
	}
	// DOWN warns about irreversible column modifications.
	if !strings.Contains(down, "WARNING") {
		t.Errorf("DOWN should warn about column modifications:\n%s", down)
	}
}

func TestGenerateFile_WritesFileWithGoosePragmas(t *testing.T) {
	g := NewDefaultMigrationGenerator("postgresql")
	desired := &DatabaseSchema{Version: "1.0.0"}
	diff := &SchemaDiff{
		HasChanges: true,
		TablesDropped: []Table{
			{Name: "gone", Columns: []Column{{Name: "id", Type: "integer"}}},
		},
		Summary: DiffSummary{TablesDropped: 1, DestructiveChanges: 1, TotalChanges: 1, SafeToApply: false},
	}
	mig, err := g.Generate(context.Background(), diff, desired)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	// A destructive diff must carry warnings.
	if len(mig.Warnings) == 0 {
		t.Error("expected warnings for a destructive diff")
	}

	outDir := t.TempDir()
	path, err := g.GenerateFile(context.Background(), mig, outDir)
	if err != nil {
		t.Fatalf("GenerateFile: %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	content := string(data)
	if !strings.Contains(content, "-- +goose Up") {
		t.Errorf("file missing goose Up pragma:\n%s", content)
	}
	if !strings.Contains(content, "-- +goose Down") {
		t.Errorf("file missing goose Down pragma:\n%s", content)
	}
	if !strings.Contains(content, "-- WARNINGS:") {
		t.Errorf("file missing warnings section:\n%s", content)
	}
	if filepath.Ext(path) != ".sql" {
		t.Errorf("expected .sql extension, got %s", path)
	}
}

